export function translate(language, keyPath) {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
  const fallbackDict = TRANSLATIONS.en;
  const keys = keyPath.split('.');
  let current = dict;
  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k];
    } else {
      current = undefined;
      break;
    }
  }
  if (typeof current === 'string') return current;

  let fb = fallbackDict;
  for (const k of keys) {
    if (fb && typeof fb === 'object' && k in fb) {
      fb = fb[k];
    } else {
      return keyPath;
    }
  }
  return typeof fb === 'string' ? fb : keyPath;
}

export function getLocalizedField(item, field, language) {
  if (!item) return '';
  if (language === 'kn' && item[`${field}_kn`]) return item[`${field}_kn`];
  if (language !== 'en' && item.translations?.[language]?.[field]) {
    return item.translations[language][field];
  }
  return item[field] || '';
}
