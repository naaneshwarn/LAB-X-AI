export function localizeClientParamError(rawError, lang = 'en') {
  const code = (lang || 'en').slice(0, 2);
  const low = String(rawError || '').toLowerCase();
  if (low.includes('resistance')) {
    return {
      en: rawError,
      kn: 'ಶಾರ್ಟ್ ಸರ್ಕ್ಯೂಟ್ ತಡೆಯಲು ಪ್ರತಿರೋಧ R > 0 Ω ಆಗಿರಬೇಕು (I = V / R).',
      hi: 'शॉर्ट सर्किट से बचने के लिए प्रतिरोध R > 0 Ω होना चाहिए (I = V / R)।',
      te: 'షార్ట్ సర్క్యూట్ నివారించడానికి ప్రతిఘటన R > 0 Ω ఉండాలి (I = V / R).',
      ta: 'குறுக்கு மின்சுற்றைத் தவிர்க்க மின்தடை R > 0 Ω ஆக இருக்க வேண்டும் (I = V / R).',
    }[code] || rawError;
  }
  if (low.includes('leading coefficient')) {
    return {
      en: rawError,
      kn: 'ವರ್ಗ ಸಮೀಕರಣಕ್ಕೆ ಗುಣಾಂಕ a ≠ 0 ಆಗಿರಬೇಕು.',
      hi: 'द्विघात समीकरण के लिए गुणांक a ≠ 0 होना चाहिए।',
      te: 'వర్గ సమీకరణానికి గుణకం a ≠ 0 ఉండాలి.',
      ta: 'இருபடிச் சமன்பாட்டிற்கு குணகம் a ≠ 0 ஆக இருக்க வேண்டும்.',
    }[code] || rawError;
  }
  if (low.includes('molarity')) {
    return {
      en: rawError,
      kn: 'pH ಲೆಕ್ಕಹಾಕಲು ಮೊಲಾರಿಟಿ ಧನಾತ್ಮಕವಾಗಿರಬೇಕು (> 0 M).',
      hi: 'pH गणना के लिए मोलरता धनात्मक (> 0 M) होनी चाहिए।',
      te: 'pH లెక్కించడానికి మోలారిటీ ధనాత్మకంగా (> 0 M) ఉండాలి.',
      ta: 'pH கணக்கிட மோலாரிட்டி நேர்மறையாக (> 0 M) இருக்க வேண்டும்.',
    }[code] || rawError;
  }
  return rawError;
}

